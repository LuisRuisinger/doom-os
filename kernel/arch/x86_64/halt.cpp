#include "kernel/core/halt.hpp"

namespace kernel::core {

// =================================================================================================
// Halt
//
// Interrupts off first, so an already-pending one cannot wake the core back out of hlt.
// =================================================================================================

[[noreturn]] void halt_forever()
{
    for (;;) {
        asm volatile("cli; hlt");
    }
}

}  // namespace kernel::core
